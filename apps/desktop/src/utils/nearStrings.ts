export type NearStringKey = keyof typeof NEAR_STRINGS;

/** Plain text with `{vars}` substituted and `**bold**` markers removed (labels, aria text). */
export function nt(key: NearStringKey, vars?: Record<string, string | number>): string {
    return fill(NEAR_STRINGS[key], vars).replace(/\*\*(.+?)\*\*/g, '$1');
}

/** Splits a string into plain and bold runs (for rendering `**x**` as `<b>`). */
export function ntRuns(key: NearStringKey, vars?: Record<string, string | number>): { text: string; bold: boolean }[] {
    const out: { text: string; bold: boolean }[] = [];
    const s = fill(NEAR_STRINGS[key], vars);
    const re = /\*\*(.+?)\*\*/g;
    let last = 0;
    for (let m = re.exec(s); m; m = re.exec(s)) {
        if (m.index > last) out.push({ text: s.slice(last, m.index), bold: false });
        out.push({ text: m[1], bold: true });
        last = m.index + m[0].length;
    }
    if (last < s.length) out.push({ text: s.slice(last), bold: false });
    return out;
}

function fill(s: string, vars?: Record<string, string | number>): string {
    return s.replace(/\{(\w+)\}/g, (m, k: string) => (vars && vars[k] != null ? String(vars[k]) : m));
}
