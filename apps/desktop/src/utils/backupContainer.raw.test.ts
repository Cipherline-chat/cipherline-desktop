import { describe, it, expect, beforeAll } from 'vitest';
import { readFileSync } from 'node:fs';

/**
 * Contract 11.15: the transfer profile of the v4 container — a raw 32-byte key, no key derivation.
 *
 * INTEROP, both ways, as committed tests:
 *  - phone -> desktop: the phone core (native `cl-near`, `near-v1.json` -> `transfer_container`, vendored at 30ea21d5) wrote a container
 *    under the vector's `K_xfer`; this build opens it and reads every record (below). The vector includes a SPLIT attachment
 *    (`att:<id>:1:2`, `att:<id>:2:2`), so the importer test (backupRecords) reuses it.
 *  - desktop -> phone: this build's writer's output is `test-vectors/ts-transfer-container.json`; the Rust reader (vendored cl-crypto
 *    `open_v4_raw`) opens it in `apps/desktop-host/tests/near_container_interop.rs`. The fixture is regenerated by the driver stored in it;
 *    the test below re-derives the fixture's records from this build's writer so a writer change that the Rust side has not seen fails here.
 */

beforeAll(() => { Object.assign(window, { crypto: globalThis.crypto, btoa: globalThis.btoa, atob: globalThis.atob }); });

const { ContainerWriter, openContainer, MemoryContainer, memorySource, isRawKeyContainer, FLAG_RAW_KEY, HEADER_LEN } = await import('./backupContainer');

const hex = (s: string) => Uint8Array.from(s.match(/../g)!.map(b => parseInt(b, 16)));
const VECTORS = JSON.parse(readFileSync(new URL('../../../desktop-host/vendor/cl-near/test-vectors/near-v1.json', import.meta.url), 'utf8'));
const TC = VECTORS.transfer_container;
const K_XFER = hex(VECTORS.keys.K_xfer_hex);
const enc = new TextEncoder();
const dec = new TextDecoder();

describe('raw-key container: a hostile sender cannot make the reader allocate from a declared length (M2)', () => {
    it('refuses a transfer record whose frame exceeds MAX_RAW_FRAME_BYTES, but a part-sized one opens', async () => {
        const { MAX_RAW_FRAME_BYTES } = await import('./backupContainer');
        const key = new Uint8Array(32).fill(9);
        const mk = async (n: number) => {
            const sink = new MemoryContainer();
            const w = await ContainerWriter.createRaw(key, sink);
            await w.addJson('meta', { version: 3, userId: 'u' });
            await w.addBytes('att:big', new Uint8Array(n));
            await w.finish({ userId: 'u', fingerprint: 'f' });
            return sink.bytes();
        };
        const ok = await openContainer(memorySource(await mk(1024 * 1024)), { rawKey: key });
        expect(ok.has('att:big')).toBe(true);
        await expect(openContainer(memorySource(await mk(MAX_RAW_FRAME_BYTES + 1)), { rawKey: key })).rejects.toThrow(/too large/);
    });
});

describe('raw-key container: the phone core\'s vector opens here', () => {
    it('opens the vector container under K_xfer and reads every record byte-for-byte', async () => {
        const bytes = hex(TC.container_hex);
        expect(isRawKeyContainer(bytes)).toBe(true);
        const c = await openContainer(memorySource(bytes), { rawKey: K_XFER });
        expect(c.index.userId).toBe(TC.inputs.user_id);
        expect(c.index.records.map(r => r.id)).toEqual(TC.records.map((r: { id: string }) => r.id));
        for (const r of TC.records as { id: string; plain_hex: string }[]) {
            expect(Array.from(await c.readBytes(r.id)), r.id).toEqual(Array.from(hex(r.plain_hex)));
        }
        expect(dec.decode(await c.readBytes('meta'))).toContain('small json record');
    });
    it('the vector\'s frames sit at their stated offsets and its parts hash as stated (what a receiver of the manifest would check)', async () => {
        const bytes = hex(TC.container_hex);
        for (const r of TC.records as { id: string; frame_hex: string; container_offset: number; frame_len: number }[]) {
            expect(Array.from(bytes.slice(r.container_offset, r.container_offset + r.frame_len)), r.id).toEqual(Array.from(hex(r.frame_hex)));
        }
        const T = TC.transfer;
        for (const p of T.parts as { id: string; container_offset: number; bytes: number; sha256: string }[]) {
            const part = bytes.slice(p.container_offset, p.container_offset + p.bytes);
            expect(part.length).toBe(p.bytes);
            const d = new Uint8Array(await crypto.subtle.digest('SHA-256', part));
            expect(Array.from(d).map(b => b.toString(16).padStart(2, '0')).join(''), p.id).toBe(p.sha256);
        }
        // ids are part:NNNNNN, the manifest carries no per-record optional flag, and the parts tile the file exactly
        const m = JSON.parse(T.manifest_json);
        expect(m.records.map((r: { id: string }) => r.id)).toEqual(T.send_order.map((n: number) => 'part:' + String(n).padStart(6, '0')));
        expect(m.records.every((r: object) => !('optional' in r))).toBe(true);
        expect(m.total_bytes).toBe(bytes.length);
        expect((T.parts as { bytes: number }[]).reduce((a, p) => a + p.bytes, 0)).toBe(bytes.length);
    });
    it('refuses the vector under a wrong raw key, a passphrase, or a flipped byte', async () => {
        const bytes = hex(TC.container_hex);
        const wrong = Uint8Array.from(K_XFER); wrong[0] ^= 1;
        await expect(openContainer(memorySource(bytes), { rawKey: wrong })).rejects.toThrow();
        await expect(openContainer(memorySource(bytes), 'a passphrase')).rejects.toThrow(/transfer container, not a backup/);
        const torn = Uint8Array.from(bytes); torn[24 + 44 + 10] ^= 1; // inside the live (second) sealed commit slot
        await expect(openContainer(memorySource(torn), { rawKey: K_XFER })).rejects.toThrow();
        const flagless = Uint8Array.from(bytes); flagless[3] = 0; // without the flag the header is a passphrase container
        await expect(openContainer(memorySource(flagless), { rawKey: K_XFER })).rejects.toThrow(/backup, not a device-transfer/);
    });
});

describe('raw-key container: this build\'s writer', () => {
    const key = () => Uint8Array.from({ length: 32 }, (_, i) => (i * 7 + 1) & 255);

    async function write(k: Uint8Array) {
        const sink = new MemoryContainer();
        const w = await ContainerWriter.createRaw(k, sink);
        await w.addJson('meta', { version: 1, userId: 'u1' });
        await w.addBytes('att:abc:1:1', new Uint8Array([1, 2, 3, 4, 5]));
        await w.finish({ userId: 'u1', fingerprint: 'near-transfer' });
        return sink.bytes();
    }

    it('writes the flagged header (flags 0x01, iteration field 1, no KDF) and round-trips under the same key', async () => {
        const bytes = await write(key());
        expect(bytes[3]).toBe(FLAG_RAW_KEY);
        expect(new DataView(bytes.buffer, bytes.byteOffset).getUint32(20, false)).toBe(1);
        expect(isRawKeyContainer(bytes)).toBe(true);
        const c = await openContainer(memorySource(bytes), { rawKey: key() });
        expect(c.index.records.map(r => r.id)).toEqual(['meta', 'att:abc:1:1']);
        expect(await c.readJson('meta')).toEqual({ version: 1, userId: 'u1' });
        expect(Array.from(await c.readBytes('att:abc:1:1'))).toEqual([1, 2, 3, 4, 5]);
        expect(c.index.records[0].offset).toBe(HEADER_LEN);
    });
    it('the committed fixture the Rust reader opens is what this writer makes (same records, sizes, hashes, flagged header)', async () => {
        const FIX = JSON.parse(readFileSync(new URL('../../../desktop-host/vendor/cl-near/test-vectors/ts-transfer-container.json', import.meta.url), 'utf8'));
        const k = hex(FIX.ck_hex);
        const fixed = hex(FIX.container_hex);
        const recs = FIX.records as { id: string; plain_text?: string; plain_hex?: string }[];
        const plain = (r: { plain_text?: string; plain_hex?: string }) => r.plain_text !== undefined ? enc.encode(r.plain_text) : hex(r.plain_hex!);
        const a = await openContainer(memorySource(fixed), { rawKey: k });
        const sink = new MemoryContainer();
        const w = await ContainerWriter.createRaw(k, sink);
        for (const r of recs) await w.addBytes(r.id, plain(r));
        await w.finish({ userId: FIX.user_id, fingerprint: FIX.fingerprint });
        const fresh = sink.bytes();
        const b = await openContainer(memorySource(fresh), { rawKey: k });
        const sig = (c: typeof a) => c.index.records.map(r => [r.id, r.size, r.hash, r.len, r.offset]);
        expect(sig(b)).toEqual(sig(a));
        expect(Array.from(await b.readBytes('att:ts-att-1'))).toEqual(Array.from(plain(recs[1])));
        expect(fresh.length).toBe(fixed.length);
        expect(fresh[3]).toBe(fixed[3]);
        expect(Array.from(fresh.slice(20, 24))).toEqual(Array.from(fixed.slice(20, 24)));
    });
    it('never opens under another key, a passphrase, or with a header bit it does not know', async () => {
        const bytes = await write(key());
        const other = key(); other[31] ^= 0xff;
        await expect(openContainer(memorySource(bytes), { rawKey: other })).rejects.toThrow();
        await expect(openContainer(memorySource(bytes), enc.encode('x').toString())).rejects.toThrow(/transfer container/);
        const odd = Uint8Array.from(bytes); odd[3] = 0x03;
        await expect(openContainer(memorySource(odd), { rawKey: key() })).rejects.toThrow(/does not support/);
    });
    it('rejects a key that is not 32 bytes', async () => {
        await expect(ContainerWriter.createRaw(new Uint8Array(16), new MemoryContainer())).rejects.toThrow(/32 bytes/);
        await expect(openContainer(memorySource(await write(key())), { rawKey: new Uint8Array(31) })).rejects.toThrow(/32 bytes/);
    });
    it('a passphrase container still carries flags 0 and the KDF iteration count (existing backups are unchanged)', async () => {
        const sink = new MemoryContainer();
        const w = await ContainerWriter.create('pw', sink);
        await w.addJson('meta', {});
        await w.finish({ userId: 'u', fingerprint: 'f' });
        const b = sink.bytes();
        expect(b[3]).toBe(0);
        expect(new DataView(b.buffer, b.byteOffset).getUint32(20, false)).toBe(600_000);
        expect(isRawKeyContainer(b)).toBe(false);
        await expect(openContainer(memorySource(b), { rawKey: key() })).rejects.toThrow(/backup, not a device-transfer/);
    });
});
