import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('/home/antigravity/Cipherline/node_modules/playwright-core');
const OUT = process.env.OUT ?? '/tmp';
const BASE = process.env.BASE ?? 'http://127.0.0.1:5351/harness/share-overload-offer.html';
const b = await chromium.launch({ executablePath: `${process.env.HOME}/.cache/ms-playwright/chromium-1247/chrome-linux64/chrome` });
const ctx = await b.newContext({ viewport: { width: 1280, height: 640 }, deviceScaleFactor: 2, reducedMotion: 'reduce' });
const p = await ctx.newPage();
p.on('pageerror', e => console.log('pageerror', e.message));
await p.goto(BASE, { timeout: 240000 });
const card = p.locator('[data-testid="share-overload-offer"]');
await card.waitFor({ timeout: 240000 });
await p.waitForTimeout(800);
await p.screenshot({ path: `${OUT}/overload-in-window.png` });
await card.screenshot({ path: `${OUT}/overload-card.png` });
const box = await card.boundingBox();
console.log('card', JSON.stringify(box));
await p.keyboard.press('Tab');
console.log('tab1', await p.evaluate(() => document.activeElement?.textContent?.trim()));
await p.keyboard.press('Tab');
console.log('tab2', await p.evaluate(() => document.activeElement?.textContent?.trim()));
await b.close();
