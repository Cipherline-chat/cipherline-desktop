// Installs a freshly built cl-audio wasm engine into the desktop app and regenerates everything derived from it:
//   src/audio/engine/cl_audio.wasm        the binary (source of truth for tests)
//   src/audio/engine/cl_audio.wasm.json   { crateCommit, sha256, bytes }  - staleness record
//   src/audio/engine/clAudioWasmBase64.ts the same bytes as base64 (what the renderer actually loads, like speexWasmBase64.ts:
//                                         no fetch, no CSP change, a packaged build cannot fail to find a sidecar file)
//
//   scripts/build-audio-wasm.sh                       # from the repo root, builds crates/cl-audio-wasm
//   node scripts/gen-cl-audio-wasm.mjs [path/to/cl_audio_wasm.wasm]
//
// Default input: $CARGO_TARGET_DIR (or <repo>/crates/target)/wasm32-unknown-unknown/release/cl_audio_wasm.wasm.
// Refuses to run when crates/ has uncommitted changes: the recorded commit must describe the binary.
// clAudioWasm.test.ts fails when the wasm, the json, the base64 module or the crates/ history disagree.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..', '..', '..');
const outDir = join(here, '..', 'src', 'audio', 'engine');
const git = (...a) => execFileSync('git', a, { cwd: repo, encoding: 'utf8' }).trim();

const target = process.env.CARGO_TARGET_DIR ?? join(repo, 'crates', 'target');
const input = process.argv[2] ?? join(target, 'wasm32-unknown-unknown', 'release', 'cl_audio_wasm.wasm');
const wasm = readFileSync(input);

// Markdown does not change the binary: a README edit must not make it look stale.
const CRATE_PATHS = ['crates', ':(exclude,glob)crates/**/*.md'];
if (git('status', '--porcelain', '--', ...CRATE_PATHS)) {
    console.error('crates/ has uncommitted changes: commit them first so the recorded commit describes the binary.');
    process.exit(1);
}
const crateCommit = git('log', '-1', '--format=%H', '--', ...CRATE_PATHS);
const sha256 = createHash('sha256').update(wasm).digest('hex');

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'cl_audio.wasm'), wasm);
writeFileSync(join(outDir, 'cl_audio.wasm.json'), JSON.stringify({ crateCommit, sha256, bytes: wasm.length }, null, 2) + '\n');
writeFileSync(join(outDir, 'clAudioWasmBase64.ts'),
`// GENERATED by scripts/gen-cl-audio-wasm.mjs from crates/cl-audio-wasm @ ${crateCommit.slice(0, 12)} - do not edit.
// cl-audio: nnnoiseless (RNNoise, BSD-3-Clause), sonora (WebRTC audio processing, BSD-3-Clause), rubato (MIT); see LICENSES.md.
export const CL_AUDIO_WASM_SHA256 = '${sha256}';
export const CL_AUDIO_WASM_BASE64 =
    '${wasm.toString('base64')}';
`);
console.log(`installed ${wasm.length} bytes, sha256 ${sha256}, crates commit ${crateCommit}`);
