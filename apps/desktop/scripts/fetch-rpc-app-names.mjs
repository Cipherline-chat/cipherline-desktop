#!/usr/bin/env node
/**
 * Regenerates electron/rpc-app-names.data.ts — the bundled, static map from a
 * Rich Presence application id to a display name (electron/rpc-app-names.ts).
 *
 * SOURCE: Discord's public "detectable applications" list,
 *   GET https://discord.com/api/v9/applications/detectable
 * (unauthenticated; the same list Discord's own client uses to recognise
 * games). Only `id` and `name` are kept — no icons, executables, hashes or
 * anything else. Run this at DEV/BUILD time only, by hand; the app NEVER
 * calls any Discord endpoint at runtime.
 *
 * Usage (from apps/desktop):
 *   node scripts/fetch-rpc-app-names.mjs                 # fetch + write
 *   node scripts/fetch-rpc-app-names.mjs --from list.json # from a saved copy
 *
 * Output format: one string, `<id>\t<name>` lines, sorted by id. One string
 * literal (not a 25k-key object literal) so tsc and the main process pay
 * almost nothing for it until the Rich Presence listener actually starts.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL = 'https://discord.com/api/v9/applications/detectable';
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'electron', 'rpc-app-names.data.ts');

const fromIdx = process.argv.indexOf('--from');
let list;
if (fromIdx > 0) {
    list = JSON.parse(readFileSync(process.argv[fromIdx + 1], 'utf8'));
} else {
    const res = await fetch(SOURCE_URL, { headers: { 'User-Agent': 'cipherline-build/1.0' } });
    if (!res.ok) throw new Error(`HTTP ${res.status} from ${SOURCE_URL}`);
    list = await res.json();
}
if (!Array.isArray(list)) throw new Error('expected an array');

const ID_RE = /^\d{15,21}$/;
const rows = new Map();
for (const app of list) {
    if (!app || typeof app.id !== 'string' || typeof app.name !== 'string') continue;
    if (!ID_RE.test(app.id)) continue;
    // One line per entry: no tabs/newlines/controls; same 100-char cap the API puts on a game name.
    // eslint-disable-next-line no-control-regex
    const name = app.name.replace(/[\u0000-\u001f\u007f-\u009f]/g, ' ').replace(/\s+/g, ' ').trim();
    if (!name || name.length > 100) continue;
    rows.set(app.id, name);
}
const ids = [...rows.keys()].sort((a, b) => (a.length - b.length) || (a < b ? -1 : a > b ? 1 : 0));
const body = ids.map((id) => `${id}\t${rows.get(id)}`).join('\n');
const generated = new Date().toISOString().slice(0, 10);

writeFileSync(out, `/* eslint-disable */
// GENERATED by scripts/fetch-rpc-app-names.mjs on ${generated} — do not edit by hand.
// Source: ${SOURCE_URL} (Discord's public detectable-applications list).
// Kept: application id + name only (${ids.length} entries). See electron/rpc-app-names.ts.
export const RPC_APP_NAMES_TSV: string = ${JSON.stringify(body)};
`);
console.log(`wrote ${ids.length} entries (${Buffer.byteLength(body)} bytes) to ${out}`);
