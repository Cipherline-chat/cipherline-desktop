// Regenerates src/utils/speexWasmBase64.ts from the installed
// @sapphi-red/speex-preprocess-wasm package. Run after bumping that dependency:
//   node scripts/gen-speex-wasm.mjs
// speexWasmBase64.test.ts fails if the checked-in file drifts from the package.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
// package.json is not in the package's exports map, so go through the wasm subpath.
const wasmPath = require.resolve('@sapphi-red/speex-preprocess-wasm/speex.wasm');
const wasm = readFileSync(wasmPath);
const version = JSON.parse(readFileSync(join(dirname(wasmPath), '..', 'package.json'), 'utf8')).version;
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'utils', 'speexWasmBase64.ts');
writeFileSync(out,
`// GENERATED by scripts/gen-speex-wasm.mjs from @sapphi-red/speex-preprocess-wasm@${version} - do not edit.
// SpeexDSP (BSD-3-Clause, Xiph.org Foundation); see LICENSES.md.
export const SPEEX_WASM_PACKAGE_VERSION = '${version}';
export const SPEEX_WASM_BASE64 =
    '${wasm.toString('base64')}';
`);
console.log(`wrote ${out} (${wasm.length} wasm bytes)`);
